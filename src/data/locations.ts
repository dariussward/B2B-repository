export function getLocationById(id: string): LocationProfile | undefined {
  return locations.find((l) => l.id === id);
}

export function getTopLocations(n = 3): LocationProfile[] {
  return [...locations]
    .sort((a, b) => b.overallScore - a.overallScore)
    .slice(0, n);
}

/** Ranked shortlist for a city (e.g. Irvine) by overall metric fit. */
export function getTopLocationsInCity(
  city: string,
  n = 5,
): LocationProfile[] {
  const needle = city.trim().toLowerCase();
  return [...locations]
    .filter((l) => l.city.toLowerCase() === needle)
    .sort((a, b) => b.overallScore - a.overallScore)
    .slice(0, n);
}
