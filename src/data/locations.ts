import type { LocationProfile } from '../types';
import {
  buildMetrics,
  computeOverallScore,
  recommendationFromScore,
} from '../lib/scoring';

function finalize(
  base: Omit<LocationProfile, 'metrics' | 'overallScore' | 'recommendation'> & {
    demographicsFit: number;
    developmentImpact: number;
    metricInsights?: Parameters<typeof buildMetrics>[0]['insights'];
  },
): LocationProfile {
  const metrics = buildMetrics({
    population: base.population,
    medianIncome: base.medianIncome,
    daytimePopulation: base.daytimePopulation,
    walkScore: base.walkScore,
    transitScore: base.transitScore,
    demographicsFit: base.demographicsFit,
    competitorsNearby: base.competitorsNearby,
    developmentImpact: base.developmentImpact,
    unemploymentRate: base.unemploymentRate,
    avgCommercialRent: base.avgCommercialRent,
    growthRate5yr: base.growthRate5yr,
    insights: base.metricInsights,
  });
  const overallScore = computeOverallScore(metrics);
  return {
    id: base.id,
    name: base.name,
    city: base.city,
    state: base.state,
    region: base.region,
    lat: base.lat,
    lng: base.lng,
    tradeArea: base.tradeArea,
    summary: base.summary,
    population: base.population,
    medianIncome: base.medianIncome,
    householdSize: base.householdSize,
    medianAge: base.medianAge,
    daytimePopulation: base.daytimePopulation,
    unemploymentRate: base.unemploymentRate,
    growthRate5yr: base.growthRate5yr,
    competitorsNearby: base.competitorsNearby,
    avgCommercialRent: base.avgCommercialRent,
    walkScore: base.walkScore,
    transitScore: base.transitScore,
    demographics: base.demographics,
    developments: base.developments,
    metrics,
    overallScore,
    recommendation: recommendationFromScore(overallScore),
  };
}

